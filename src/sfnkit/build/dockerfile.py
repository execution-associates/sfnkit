"""Dockerfile for one image variant.

Two layouts:
  * The AWS Lambda Python base (no custom base): deps go into ``${LAMBDA_TASK_ROOT}`` next to the code.
    Lambda starts it with its own bootstrap; Batch and ECS start ``python -m sfnkit.runtime.container``.
  * A custom base (``sfnkit.Image(base=...)``): sfnkit lives under ``/opt/sfnkit``. ``/opt/sfnkit/bin/python``
    is the interpreter every entrypoint uses: the base's own Python, a standalone one installed with uv,
    or a launcher that activates a conda env first. Lambda reaches it through ``awslambdaric``.
"""

from __future__ import annotations

import shlex

from sfnkit.app import ImageVariant
from sfnkit.compute.lambda_ import HANDLER

# Pinned so a content hash means the same image every time.
UV_VERSION = "0.13.7"
MICROMAMBA_VERSION = "2.3.3"
LAMBDA_RIC = "awslambdaric>=3"
OPT = "/opt/sfnkit"
PY = f"{OPT}/bin/python"

_PLATFORMS = {
    "x86_64": ("linux/amd64", "x86_64-manylinux_2_28"),
    "arm64": ("linux/arm64", "aarch64-manylinux_2_28"),
}


def docker_platform(architecture: str) -> str:
    try:
        return _PLATFORMS[architecture][0]
    except KeyError:
        raise ValueError(f"unsupported architecture {architecture!r} (x86_64 or arm64)") from None


def _check(image: ImageVariant) -> None:
    if image.architecture not in _PLATFORMS:
        raise ValueError(f"unsupported architecture {image.architecture!r} (x86_64 or arm64)")
    if image.runtime not in ("lambda", "container"):
        raise ValueError(f"unknown image runtime {image.runtime!r}")


def render_dockerfile(image: ImageVariant, uv_version: str = UV_VERSION) -> str:
    _check(image)
    if image.custom:
        return _custom(image, uv_version)
    return _lambda_base(image, uv_version)


def _lambda_base(image: ImageVariant, uv_version: str) -> str:
    py_platform = _PLATFORMS[image.architecture][1]
    lines = [
        "# Generated by sfnkit. Do not edit; it is rewritten on every build.",
        f"FROM public.ecr.aws/lambda/python:{image.python}",
    ]
    if image.system_packages:
        pkgs = " ".join(shlex.quote(p) for p in image.system_packages)
        # Lambda's AL2023 base images ship microdnf, not dnf/yum.
        lines.append(f"RUN microdnf install -y {pkgs} && microdnf clean all")
    lines.append(f"COPY --from=ghcr.io/astral-sh/uv:{uv_version} /uv /bin/uv")
    if image.deps:
        lines += [
            "COPY requirements.txt /opt/sfnkit-build/requirements.txt",
            (
                'RUN uv pip install --no-cache --target "${LAMBDA_TASK_ROOT}" '
                f"--python-version {image.python} --python-platform {py_platform} "
                "-r /opt/sfnkit-build/requirements.txt"
            ),
        ]
    lines += [
        "COPY sfnkit/ ${LAMBDA_TASK_ROOT}/sfnkit/",
        "COPY project/ ${LAMBDA_TASK_ROOT}/",
    ]
    if image.runtime == "container":
        # Batch/ECS run the same base image, but without Lambda's bootstrap entrypoint.
        lines += [
            "ENV PYTHONPATH=${LAMBDA_TASK_ROOT}",
            'ENTRYPOINT ["/var/lang/bin/python3", "-m", "sfnkit.runtime.container"]',
            "CMD []",
        ]
    else:
        lines.append(f'CMD ["{HANDLER}"]')
    lines.append("")
    return "\n".join(lines)


def _system_packages(pkgs: tuple[str, ...]) -> str:
    q = " ".join(shlex.quote(p) for p in pkgs)
    return (
        "RUN set -eu; "
        "if command -v apt-get >/dev/null 2>&1; then "
        f"apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends {q} "
        "&& rm -rf /var/lib/apt/lists/*; "
        f"elif command -v apk >/dev/null 2>&1; then apk add --no-cache {q}; "
        f"elif command -v microdnf >/dev/null 2>&1; then microdnf install -y {q} && microdnf clean all; "
        f"elif command -v dnf >/dev/null 2>&1; then dnf install -y {q} && dnf clean all; "
        f"elif command -v yum >/dev/null 2>&1; then yum install -y {q} && yum clean all; "
        'else echo "sfnkit: the base image has no apt-get, apk, dnf or yum for system_packages" >&2; '
        "exit 1; fi"
    )


def _python(image: ImageVariant) -> str:
    """Point /opt/sfnkit/bin/python at the interpreter this image runs."""
    mode = image.python_mode
    find_base = (
        'py=""; for c in python3 python; do p="$(command -v "$c" || true)"; '
        "if [ -n \"$p\" ] && \"$p\" -c 'import sys; sys.exit(sys.version_info < (3, 12))' 2>/dev/null; "
        'then py="$p"; break; fi; done; '
    )
    version = image.python if mode in (None, "base") else mode
    install = (
        f"UV_PYTHON_INSTALL_DIR={OPT}/python uv python install --no-bin {version} && "
        f'py="$(UV_PYTHON_INSTALL_DIR={OPT}/python uv python find --managed-python {version})"; '
    )
    if mode == "base":
        body = find_base + (
            'if [ -z "$py" ]; then echo "sfnkit: python=\\"base\\" but the base image has no python3 >= 3.12" '
            ">&2; exit 1; fi; "
        )
    elif mode is None:
        body = find_base + f'if [ -z "$py" ]; then {install}fi; '
    else:
        body = install
    return f'RUN set -eu; mkdir -p {OPT}/bin; {body}ln -sf "$py" {PY}; {PY} --version'


def _conda(image: ImageVariant) -> list[str]:
    channels = " ".join(f"-c {shlex.quote(c)}" for c in image.channels)
    if image.python_mode:
        python = f"python={image.python_mode}"
    else:  # the newest the solver can fit, up to the workflow's version: brand-new Pythons lag in bioconda
        major, minor = (int(x) for x in image.python.split(".")[:2])
        python = f"python>=3.12,<{major}.{minor + 1}"
    specs = " ".join(shlex.quote(s) for s in (python, *image.conda))
    mm = f"mambaorg/micromamba:{MICROMAMBA_VERSION}"
    return [
        f"COPY --from={mm} /bin/micromamba /usr/local/bin/micromamba",
        # Slim bases ship no CA certificates; borrow micromamba's own for the download.
        f"COPY --from={mm} /etc/ssl/certs/ca-certificates.crt /opt/sfnkit-build/ca.crt",
        (
            f"RUN micromamba create -y -p {OPT}/env --root-prefix {OPT}/mamba --cacert-path "
            f"/opt/sfnkit-build/ca.crt --override-channels --strict-channel-priority {channels} {specs} "
            f"&& rm -rf {OPT}/mamba/pkgs /opt/sfnkit-build/ca.crt"  # the package cache: not needed at run time
        ),
        # Activation scripts (GDAL_DATA, PROJ_DATA and so on) are captured once, at build time, then the
        # launcher sources them before every run: Lambda's read-only filesystem rules out `micromamba run`.
        # PATH is set by the launcher instead of the snapshot, which would pin the build's PATH.
        (
            f"RUN mkdir -p {OPT}/bin && MAMBA_ROOT_PREFIX={OPT}/mamba micromamba shell activate -s posix "
            f"{OPT}/env | grep -v -e '^PS1=' -e '^export PATH=' > {OPT}/activate.sh && "
            f"printf '#!/bin/sh\\nPATH={OPT}/env/bin:$PATH; export PATH\\n. {OPT}/activate.sh\\n"
            f"exec {OPT}/env/bin/python \"$@\"\\n' > {PY} && chmod 755 {PY} && {PY} --version"
        ),
    ]


def _custom(image: ImageVariant, uv_version: str) -> str:
    lines = [
        "# Generated by sfnkit. Do not edit; it is rewritten on every build.",
        f"FROM {image.base}",
        "USER root",  # installs need root; bases like micromamba's default to an unprivileged user
    ]
    if image.system_packages:
        lines.append(_system_packages(image.system_packages))
    lines.append(f"COPY --from=ghcr.io/astral-sh/uv:{uv_version} /uv /usr/local/bin/uv")
    lines += _conda(image) if image.conda else [_python(image)]
    lines += [
        "COPY requirements.txt /opt/sfnkit-build/requirements.txt",
        # Into the interpreter's own environment, so packages the base or the conda env already has are
        # reused instead of shadowed by a second copy.
        (
            f"RUN uv pip install --no-cache --python {PY} --break-system-packages "
            "-r /opt/sfnkit-build/requirements.txt && rm -rf /opt/sfnkit-build"
        ),
        f"COPY sfnkit/ {OPT}/app/sfnkit/",
        f"COPY project/ {OPT}/app/",
        f"ENV PYTHONPATH={OPT}/app",
    ]
    if image.runtime == "container":
        lines += [f'ENTRYPOINT ["{PY}", "-m", "sfnkit.runtime.container"]', "CMD []"]
    else:
        lines += [f'ENTRYPOINT ["{PY}", "-m", "awslambdaric"]', f'CMD ["{HANDLER}"]']
    lines.append("")
    return "\n".join(lines)


def requirements(image: ImageVariant) -> list[str]:
    """pip requirements for the image: the deps, plus what sfnkit's runtime needs on a custom base (the
    Lambda base already ships boto3)."""
    reqs = list(image.deps)
    if image.custom:
        names = {_name(d) for d in reqs}
        if "boto3" not in names:
            reqs.append("boto3>=1.35")
        if image.runtime == "lambda" and "awslambdaric" not in names:
            reqs.append(LAMBDA_RIC)
    return reqs


def _name(req: str) -> str:
    out = ""
    for ch in req:
        if not (ch.isalnum() or ch in "-_."):
            break
        out += ch
    return out.lower().replace("_", "-")


def render_requirements(image: ImageVariant) -> str:
    return "".join(f"{d}\n" for d in requirements(image))
